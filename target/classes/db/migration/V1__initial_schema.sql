CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('TEACHER', 'SECRETARY')),
    room VARCHAR(3),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (room IS NULL OR room IN ('PPA', 'PPB', 'PPC', 'M1A', 'M1B', 'M1C', 'M2A', 'M2B', 'M2C'))
);

CREATE TABLE equipment (
    id BIGINT PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES app_user(id),
    teacher_name VARCHAR(120) NOT NULL,
    room VARCHAR(3) NOT NULL,
    equipment_id BIGINT NOT NULL REFERENCES equipment(id),
    pickup_date DATE NOT NULL,
    return_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (return_date >= pickup_date)
);

CREATE INDEX booking_equipment_dates ON booking (equipment_id, status, pickup_date, return_date);
CREATE INDEX booking_teacher ON booking (teacher_id);

